BANKS = {1: M1, 2: M2, 3: M3, 4: M4, 5: M5}


def build():
    questions, options = [], []
    for mod, groups in BANKS.items():
        for gi, (obj, qtype, diff, variants) in enumerate(groups, start=1):
            group = f"M{mod}-G{gi:02d}"
            for vi, (scenario, text, opts, expl) in enumerate(variants, start=1):
                code = f"{group}-V{vi}"
                qid = str(uuid.uuid5(NS, code))
                correct = [o for o in opts if o.startswith("*")]
                assert correct, code
                if qtype != "multi":
                    assert len(correct) == 1, code
                else:
                    assert len(correct) >= 2, code
                questions.append({
                    "id": qid, "code": code, "module_id": MODULES[mod], "objective_index": obj,
                    "question_type": TYPES[qtype], "question_text": text, "scenario_text": scenario,
                    "difficulty": diff, "variant_group": group, "variant_number": vi,
                    "explanation": expl, "status": "active",
                })
                for oi, o in enumerate(opts, start=1):
                    options.append({
                        "id": str(uuid.uuid5(NS, f"{code}-O{oi}")), "question_id": qid,
                        "option_text": o.lstrip("*"), "is_correct": o.startswith("*"), "sort_order": oi,
                    })
    return questions, options


def post(path, rows):
    url = os.environ["SUPABASE_URL"] + f"/rest/v1/{path}"
    key = os.environ["SUPABASE_SERVICE_ROLE_KEY"]
    req = urllib.request.Request(url, data=json.dumps(rows).encode(), method="POST", headers={
        "apikey": key, "Authorization": f"Bearer {key}", "Content-Type": "application/json",
        "Prefer": "resolution=merge-duplicates,return=minimal"})
    urllib.request.urlopen(req).read()


if __name__ == "__main__":
    qs, os_ = build()
    summary = {}
    for q in qs:
        m = [k for k, v in MODULES.items() if v == q["module_id"]][0]
        s = summary.setdefault(m, {"questions": 0, "groups": set(), "variant_groups": set(), "easy": set(), "medium": set(), "hard": set()})
        s["questions"] += 1; s["groups"].add(q["variant_group"]); s[q["difficulty"]].add(q["variant_group"])
        if q["variant_number"] == 2: s["variant_groups"].add(q["variant_group"])
    for m, s in sorted(summary.items()):
        print(f"Module {m}: {s['questions']} questions, {len(s['groups'])} groups, "
              f"{len(s['variant_groups'])} variant groups, groups by difficulty "
              f"E{len(s['easy'])}/M{len(s['medium'])}/H{len(s['hard'])}")
    with open(os.path.join(os.path.dirname(__file__), "assessment_bank.json"), "w") as f:
        json.dump({"questions": qs, "options": os_}, f, ensure_ascii=False, indent=1)
    if "--apply" in sys.argv:
        post("assessment_questions?on_conflict=code", qs)
        post("assessment_question_options?on_conflict=id", os_)
        print("applied")
